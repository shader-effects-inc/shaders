/**
 * Build a single-file ESM bundle of `shaders/react` for CDN consumption
 * (Framer code components, etc.). The published `./react` entry point is a
 * thin re-export of ~100 sibling shader modules — efficient for tree-shaking
 * Vite/webpack consumers but unfit for CDN delivery, which would require one
 * HTTP request per shader. This pre-bundled artifact bakes everything into
 * one file and externalizes React so Framer (and anyone else with their own
 * React) can serve it directly via jsdelivr/unpkg.
 *
 * Output: `dist/react/bundle.js` — minified, ~2 MB, version-pinned via the
 * usual npm tarball mechanics. Consumed via:
 *   https://cdn.jsdelivr.net/npm/shaders@<version>/dist/react/bundle.js
 */
async function bundleReactForFramer() {
  const entry = path.join(distDir, 'react/index.js')
  const outFile = path.join(distDir, 'react/bundle.js')

  if (!await fs.pathExists(entry)) {
    throw new Error(`bundleReactForFramer: entry not found at ${entry}`)
  }

  const pkgVersion = (await fs.readJSON(path.join(packageDir, 'package.json'))).version

  const result = await esbuild.build({
    entryPoints: [entry],
    bundle: true,
    format: 'esm',
    platform: 'browser',
    target: 'es2022',
    outfile: outFile,
    external: ['react', 'react-dom', 'react/jsx-runtime'],
    minify: true,
    sourcemap: false,
    legalComments: 'none',
    metafile: true,
    banner: {
      js: `/* shaders@${pkgVersion}/react — bundled for CDN consumption (Framer code components, etc.). https://shaders.com */`,
    },
  })

  const sizeBytes = result.metafile ? Object.values(result.metafile.outputs)[0]?.bytes ?? 0 : 0
  console.log(`  ✓ Bundled react/bundle.js (${(sizeBytes / 1024).toFixed(0)} KB minified)`)
}

/**
 * Build a single-file ESM bundle of `shaders/js` for direct CDN consumption
 * (WordPress, plain HTML, no bundler required).
 *
 * Output: `dist/js/bundle.js` — minified, version-pinned via the package banner.
 * CDN URL:
 *   https://cdn.jsdelivr.net/npm/shaders@<version>/dist/js/bundle.js
 */
async function bundleJsForCDN() {
  const entry = path.join(distDir, 'js/index.js')
  const outFile = path.join(distDir, 'js/bundle.js')

  if (!await fs.pathExists(entry)) {
    throw new Error(`bundleJsForCDN: entry not found at ${entry}`)
  }

  const pkgVersion = (await fs.readJSON(path.join(packageDir, 'package.json'))).version

  const result = await esbuild.build({
    entryPoints: [entry],
    bundle: true,
    format: 'esm',
    platform: 'browser',
    target: 'es2022',
    outfile: outFile,
    minify: true,
    sourcemap: false,
    legalComments: 'none',
    metafile: true,
    banner: {
      js: `/* shaders@${pkgVersion}/js — ESM bundle for CDN consumption (no bundler required). https://shaders.com */`,
    },
  })

  const sizeBytes = result.metafile ? Object.values(result.metafile.outputs)[0]?.bytes ?? 0 : 0
  console.log(`  ✓ Bundled js/bundle.js (${(sizeBytes / 1024).toFixed(0)} KB minified)`)
}

/**
 * Build the `shaders/config` entry (src/config.ts → dist/config.js + .d.ts):
 * the `defineConfig` helper that `npx shaders connect` writes into a project's
 * shaders.config.ts. Dependency-free, so a plain esbuild transform + tsc
 * declaration emit is all it needs.
 */
async function bundleConfig() {
  const entry = path.join(packageDir, 'src/config.ts')
  await esbuild.build({
    entryPoints: [entry],
    format: 'esm',
    platform: 'neutral',
    target: 'es2022',
    outfile: path.join(distDir, 'config.js')
  })
  execFileSync('npx', [
    'tsc', entry,
    '--declaration', '--emitDeclarationOnly',
    '--outDir', distDir,
    '--module', 'esnext', '--target', 'es2022', '--moduleResolution', 'bundler', '--skipLibCheck'
  ], { cwd: packageDir, stdio: 'inherit' })
  console.log('  ✓ Built config.js + config.d.ts')
}

/**
 * Bundle the CLI (src/cli.ts) into dist/cli.js, exposed via the package.json
 * "bin" field so `npx shaders connect` / `install-mcp` work. add-mcp, consola,
 * nypm, pkg-types and @clack/prompts are devDependencies bundled in here, so
 * the published package gains no runtime dependencies.
 */
async function bundleCli() {
  const entry = path.join(packageDir, 'src/cli.ts')
  const outFile = path.join(distDir, 'cli.js')

  if (!await fs.pathExists(entry)) {
    throw new Error(`bundleCli: entry not found at ${entry}`)
  }

  const pkgVersion = (await fs.readJSON(path.join(packageDir, 'package.json'))).version

  const result = await esbuild.build({
    entryPoints: [entry],
    bundle: true,
    format: 'esm',
    platform: 'node',
    target: 'node18',
    outfile: outFile,
    minify: true,
    sourcemap: false,
    legalComments: 'none',
    metafile: true,
    // Prefer ESM entry points: jsonc-parser (via add-mcp) ships a UMD main
    // whose dynamic requires can't be bundled statically
    mainFields: ['module', 'main'],
    define: {
      __SHADERS_CLI_VERSION__: JSON.stringify(pkgVersion)
    },
    banner: {
      // Shebang for the bin entry, plus a createRequire shim so CJS
      // dependencies bundled into this ESM output can still require()
      js: [
        '#!/usr/bin/env node',
        `/* shaders@${pkgVersion} CLI — npx shaders connect | install-mcp. https://shaders.com */`,
        'import { createRequire as __cliCreateRequire } from "module";',
        'const require = __cliCreateRequire(import.meta.url);'
      ].join('\n')
    }
  })

  const sizeBytes = result.metafile ? Object.values(result.metafile.outputs)[0]?.bytes ?? 0 : 0
  console.log(`  ✓ Bundled cli.js (${(sizeBytes / 1024).toFixed(0)} KB minified)`)
}

/**
 * Main build function
 */
async function build() {
  try {
    console.log('📦 Building shaders package...')

    await prepareDistDirectory()
    await copyFrameworkBuilds()
    await copySvelteSource()
    await copyCorePackage()
    await rewriteJsImports()
    await verifyTypeImports()
    await bundleReactForFramer()
    await bundleJsForCDN()
    await bundleConfig()
    await bundleCli()
    await updatePackageExports()
    const shaderCount = await generateRegistry()
    await generateSkillDocs()
    await createIndexFile()

    // Copy LICENSE and README if they exist
    const licensePath = path.join(rootDir, 'LICENSE')
    if (await fs.pathExists(licensePath)) {
      await fs.copy(licensePath, path.join(packageDir, 'LICENSE'))
    }

    const readmePath = path.join(rootDir, 'README.md')
    if (await fs.pathExists(readmePath)) {
      await fs.copy(readmePath, path.join(packageDir, 'README.md'))
    }

    const { size } = await fs.stat(distDir)
    console.log(`✅ Built shaders package (${shaderCount} shaders, ${(size / 1024 / 1024).toFixed(2)} MB)`)

  } catch (error) {
    console.error('❌ Build failed:', error)
    process.exit(1)
  }
}

// Check if running directly (not imported)
if (import.meta.url === `file://${process.argv[1]}`) {
  build()
}