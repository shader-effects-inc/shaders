/**
 * Copy Svelte source files to dist/svelte/source for the `svelte` export condition.
 * This enables SSR compatibility in SvelteKit by letting the bundler compile .svelte
 * files itself rather than using the pre-compiled client-only JS.
 */
async function copySvelteSource() {
  const svelteSrcDir = path.join(rootDir, 'packages/svelte/src/lib')
  const svelteSrcIndexPath = path.join(svelteSrcDir, 'index.ts')
  const sourceTargetDir = path.join(distDir, 'svelte/source')

  if (!await fs.pathExists(svelteSrcDir) || !await fs.pathExists(svelteSrcIndexPath)) {
    console.log('  ⚠ Svelte source not found, skipping dist/svelte/source generation')
    return
  }

  await fs.ensureDir(sourceTargetDir)

  // Copy all .svelte files, preserving directory structure, excluding the code-gen template
  const svelteSrcFiles = await findFiles(svelteSrcDir, /\.svelte$/)
  let filesCopied = 0

  for (const srcFile of svelteSrcFiles) {
    if (path.basename(srcFile) === 'component.template.svelte') continue

    const relativePath = path.relative(svelteSrcDir, srcFile)
    const targetFile = path.join(sourceTargetDir, relativePath)
    await fs.ensureDir(path.dirname(targetFile))

    let content = await fs.readFile(srcFile, 'utf-8')

    if (content.includes('shaders-core')) {
      // Calculate relative path from this file's directory to dist/core
      const relativeToCoreDir = path.relative(path.dirname(targetFile), path.join(distDir, 'core'))
      const normalizedPath = relativeToCoreDir.split(path.sep).join('/')

      content = content.replace(/'shaders-core\/telemetry'/g, `'${normalizedPath}/telemetry/index.js'`)
      content = content.replace(/"shaders-core\/telemetry"/g, `"${normalizedPath}/telemetry/index.js"`)
      content = content.replace(/'shaders-core\/utilities\/([^']+)'/g, `'${normalizedPath}/utilities/$1/index.js'`)
      content = content.replace(/"shaders-core\/utilities\/([^"]+)"/g, `"${normalizedPath}/utilities/$1/index.js"`)
      content = content.replace(/'shaders-core\/([^']+)'/g, `'${normalizedPath}/shaders/$1/index.js'`)
      content = content.replace(/"shaders-core\/([^"]+)"/g, `"${normalizedPath}/shaders/$1/index.js"`)
      content = content.replace(/'shaders-core'/g, `'${normalizedPath}/index.js'`)
      content = content.replace(/"shaders-core"/g, `"${normalizedPath}/index.js"`)
    }

    await fs.writeFile(targetFile, content)
    filesCopied++
  }

  // Generate source/index.js from index.ts — .svelte re-exports are valid JS already;
  // the generatePresetCode path needs updating to point to the compiled dist file, and
  // type-only re-exports must be stripped (they are TypeScript syntax, invalid in .js —
  // plain Vite + Svelte consumers resolve this file via the `svelte` condition and fail
  // to parse them)
  let indexContent = await fs.readFile(svelteSrcIndexPath, 'utf-8')
  indexContent = indexContent.replace(
    `export { generatePresetCode } from './utils/generatePresetCode'`,
    `export { generatePresetCode } from '../utils/generatePresetCode.js'`
  )
  indexContent = indexContent.replace(
    /^(export|import)\s+type\s+\{[^}]*\}(\s+from\s+['"][^'"]+['"])?;?\s*$/gm,
    ''
  )
  await fs.writeFile(path.join(sourceTargetDir, 'index.js'), indexContent)

  console.log(`  ✓ Copied ${filesCopied} Svelte source files to dist/svelte/source`)
}

/**
 * Rewrite shaders-core imports in JS files to relative paths
 * This is needed because we externalize shaders-core during framework builds
 */
async function rewriteJsImports() {
  const frameworks = ['vue', 'react', 'svelte', 'solid', 'js']
  let filesRewritten = 0

  for (const framework of frameworks) {
    const frameworkDir = path.join(distDir, framework)
    if (!await fs.pathExists(frameworkDir)) continue

    const jsFiles = await findFiles(frameworkDir, /\.js$/)

    for (const file of jsFiles) {
      let content = await fs.readFile(file, 'utf-8')

      if (content.includes('shaders-core')) {
        filesRewritten++

        // Calculate relative path from this file to the core directory
        const relativePath = path.relative(path.dirname(file), path.join(distDir, 'core'))
        const normalizedPath = relativePath.split(path.sep).join('/')

        // Handle telemetry separately (maps directly to core/telemetry)
        content = content.replace(/'shaders-core\/telemetry'/g, `'${normalizedPath}/telemetry/index.js'`)
        content = content.replace(/"shaders-core\/telemetry"/g, `"${normalizedPath}/telemetry/index.js"`)
        // Handle registry separately (maps directly to core/registry)
        content = content.replace(/'shaders-core\/registry'/g, `'${normalizedPath}/registry.js'`)
        content = content.replace(/"shaders-core\/registry"/g, `"${normalizedPath}/registry.js"`)
        // Handle std separately (maps directly to core/std)
        content = content.replace(/'shaders-core\/std'/g, `'${normalizedPath}/std/index.js'`)
        content = content.replace(/"shaders-core\/std"/g, `"${normalizedPath}/std/index.js"`)
        // Handle utilities separately (maps directly to core/utilities/*)
        content = content.replace(/'shaders-core\/utilities\/([^']+)'/g, `'${normalizedPath}/utilities/$1/index.js'`)
        content = content.replace(/"shaders-core\/utilities\/([^"]+)"/g, `"${normalizedPath}/utilities/$1/index.js"`)
        // Other subpaths are shaders (map to core/shaders/*)
        content = content.replace(/'shaders-core\/([^']+)'/g, `'${normalizedPath}/shaders/$1/index.js'`)
        content = content.replace(/"shaders-core\/([^"]+)"/g, `"${normalizedPath}/shaders/$1/index.js"`)
        // Main module
        content = content.replace(/'shaders-core'/g, `'${normalizedPath}/index.js'`)
        content = content.replace(/"shaders-core"/g, `"${normalizedPath}/index.js"`)

        await fs.writeFile(file, content)
      }
    }
  }

  console.log(`  ✓ Rewrote shaders-core imports in ${filesRewritten} JS files`)
}

/**
 * Verify type imports were rewritten correctly by vite-plugin-dts
 * This serves as a safety net - if any shaders-core imports remain, rewrite them
 */
async function verifyTypeImports() {
  const frameworks = ['vue', 'react', 'svelte', 'solid', 'js']
  let filesWithUnrewrittenImports = 0

  for (const framework of frameworks) {
    const frameworkDir = path.join(distDir, framework)
    if (!await fs.pathExists(frameworkDir)) continue

    const dtsFiles = await findFiles(frameworkDir, /\.d\.ts$/)

    for (const file of dtsFiles) {
      let content = await fs.readFile(file, 'utf-8')

      // Check if any shaders-core imports remain (they should have been rewritten by vite-plugin-dts)
      if (content.includes('shaders-core')) {
        filesWithUnrewrittenImports++
        console.warn(`  ⚠ Found unrewritten shaders-core import in: ${path.relative(distDir, file)}`)

        // Fallback: rewrite them here
        const relativePath = path.relative(path.dirname(file), path.join(distDir, 'core'))
        const normalizedPath = relativePath.split(path.sep).join('/')

        // Handle telemetry separately (maps directly to dist/telemetry)
        content = content.replace(/'shaders-core\/telemetry'/g, `'${normalizedPath}/telemetry'`)
        content = content.replace(/"shaders-core\/telemetry"/g, `"${normalizedPath}/telemetry"`)
        // Handle registry separately (maps directly to dist/registry)
        content = content.replace(/'shaders-core\/registry'/g, `'${normalizedPath}/registry'`)
        content = content.replace(/"shaders-core\/registry"/g, `"${normalizedPath}/registry"`)
        // Handle std separately (maps directly to dist/std)
        content = content.replace(/'shaders-core\/std'/g, `'${normalizedPath}/std'`)
        content = content.replace(/"shaders-core\/std"/g, `"${normalizedPath}/std"`)
        // Handle utilities separately (maps directly to dist/utilities/*)
        content = content.replace(/'shaders-core\/utilities\/([^']+)'/g, `'${normalizedPath}/utilities/$1'`)
        content = content.replace(/"shaders-core\/utilities\/([^"]+)"/g, `"${normalizedPath}/utilities/$1"`)
        // Other subpaths are shaders (map to dist/shaders/*)
        content = content.replace(/'shaders-core\/([^']+)'/g, `'${normalizedPath}/shaders/$1'`)
        content = content.replace(/"shaders-core\/([^"]+)"/g, `"${normalizedPath}/shaders/$1"`)
        // Main module
        content = content.replace(/'shaders-core'/g, `'${normalizedPath}'`)
        content = content.replace(/"shaders-core"/g, `"${normalizedPath}"`)

        await fs.writeFile(file, content)
      }
    }
  }

  if (filesWithUnrewrittenImports === 0) {
    console.log('  ✓ All type imports correctly rewritten by vite-plugin-dts')
  } else {
    console.log(`  ⚠ Fallback: rewrote ${filesWithUnrewrittenImports} files with remaining shaders-core imports`)
  }
}

/**
 * Deprecated (former) shader names declared in a shader's `deprecatedNames: [...]` field, read by
 * text scan of the shader's built output (the field is a pure string-literal array by convention —
 * see GpuShaderDefinition.deprecatedNames). Old names get ALIAS export entries pointing at the
 * canonical folder's files, so old deep imports (`shaders/core/DOMTexture`) keep resolving with
 * zero file duplication.
 */
async function readDeprecatedNames(shaderIndexJsPath: string): Promise<string[]> {
  if (!await fs.pathExists(shaderIndexJsPath)) return []
  const source = await fs.readFile(shaderIndexJsPath, 'utf8')
  const match = source.match(/deprecatedNames:\s*\[([^\]]*)\]/)
  if (!match) return []
  return [...match[1].matchAll(/['"`]([^'"`]+)['"`]/g)].map(m => m[1])
}

/**
 * Update package.json exports to include core subpaths
 */
async function updatePackageExports() {
  const packageJsonPath = path.join(packageDir, 'package.json')
  const pkg = await fs.readJSON(packageJsonPath)

  // Read shader list from core dist
  const shadersDirPath = path.join(distDir, 'core/shaders')
  if (!await fs.pathExists(shadersDirPath)) {
    console.log('  ⚠ No shaders directory found in core, skipping exports update')
    return
  }

  const shaderDirs = (await fs.readdir(shadersDirPath, { withFileTypes: true }))
    .filter(d => d.isDirectory())
    .map(d => d.name)

  // canonical shader name → its deprecated (former) names
  const deprecatedNamesMap: Record<string, string[]> = {}
  for (const shader of shaderDirs) {
    const deprecated = await readDeprecatedNames(path.join(shadersDirPath, shader, 'index.js'))
    if (deprecated.length) deprecatedNamesMap[shader] = deprecated
  }

  // Add core main export
  pkg.exports['./core'] = {
    types: './dist/core/index.d.ts',
    import: './dist/core/index.js',
    require: './dist/core/index.js'
  }

  // The docs manifest + llms.txt: the generated description of the std vocabulary (see
  // packages/core/scripts/docsManifest.ts). Published so agents and tools can read the
  // vocabulary of the exact version they installed.
  if (await fs.pathExists(path.join(distDir, 'core/docs-manifest.json'))) {
    pkg.exports['./docs-manifest.json'] = './dist/core/docs-manifest.json'
  }
  if (await fs.pathExists(path.join(distDir, 'core/llms.txt'))) {
    pkg.exports['./llms.txt'] = './dist/core/llms.txt'
  }

  // The public authoring surface: defineShader, wgsl, the std vocabulary, registerShader.
  if (await fs.pathExists(path.join(distDir, 'core/std/index.js'))) {
    pkg.exports['./std'] = {
      types: './dist/core/std/index.d.ts',
      import: './dist/core/std/index.js',
      require: './dist/core/std/index.js'
    }
  }

  // Add telemetry export if it exists
  if (await fs.pathExists(path.join(distDir, 'core/telemetry'))) {
    pkg.exports['./core/telemetry'] = {
      types: './dist/core/telemetry/index.d.ts',
      import: './dist/core/telemetry/index.js',
      require: './dist/core/telemetry/index.js'
    }
  }

  // Add each shader subpath export (+ alias entries for deprecated names pointing at the
  // canonical files — this also OVERWRITES the stale entry a rename leaves behind).
  for (const shader of shaderDirs) {
    const entry = {
      types: `./dist/core/shaders/${shader}/index.d.ts`,
      import: `./dist/core/shaders/${shader}/index.js`,
      require: `./dist/core/shaders/${shader}/index.js`
    }
    pkg.exports[`./core/${shader}`] = entry
    for (const oldName of deprecatedNamesMap[shader] ?? []) {
      pkg.exports[`./core/${oldName}`] = entry
    }
  }

  // Add partner SDK export
  pkg.exports['./partner'] = {
    types: './dist/partner/index.d.ts',
    import: './dist/partner/index.js',
  }

  // Build typesVersions for moduleResolution: "node" compatibility
  // This enables type resolution for older TypeScript configurations that don't read the exports field
  const typesVersions: Record<string, string[]> = {
    // Framework exports
    'vue': ['./dist/vue/index.d.ts'],
    'vue/codegen': ['./dist/vue/codegen.d.ts'],
    'react': ['./dist/react/index.d.ts'],
    'react/codegen': ['./dist/react/codegen.d.ts'],
    'svelte': ['./dist/svelte/index.d.ts'],
    'svelte/codegen': ['./dist/svelte/codegen.d.ts'],
    'solid': ['./dist/solid/index.d.ts'],
    'solid/codegen': ['./dist/solid/codegen.d.ts'],
    // Integration packages
    'js': ['./dist/js/index.d.ts'],
    'js/codegen': ['./dist/js/codegen.d.ts'],
    // Core exports
    'core': ['./dist/core/index.d.ts'],
    'core/telemetry': ['./dist/core/telemetry/index.d.ts'],
    'std': ['./dist/core/std/index.d.ts'],
    // Registry
    'registry': ['./dist/registry.d.ts'],
    'config': ['./dist/config.d.ts'],
    // Partner SDK
    'partner': ['./dist/partner/index.d.ts'],
  }

  // Add each shader to typesVersions (+ deprecated-name aliases → the canonical types)
  for (const shader of shaderDirs) {
    typesVersions[`core/${shader}`] = [`./dist/core/shaders/${shader}/index.d.ts`]
    for (const oldName of deprecatedNamesMap[shader] ?? []) {
      typesVersions[`core/${oldName}`] = [`./dist/core/shaders/${shader}/index.d.ts`]
    }
  }

  // Also add the wildcard pattern for any shaders not explicitly listed
  typesVersions['core/*'] = ['./dist/core/shaders/*/index.d.ts']

  pkg.typesVersions = { '*': typesVersions }

  await fs.writeJSON(packageJsonPath, pkg, { spaces: 2 })
  console.log(`  ✓ Added ${shaderDirs.length + 2} core exports to package.json`)
  console.log(`  ✓ Generated typesVersions with ${Object.keys(typesVersions).length} mappings`)
}

