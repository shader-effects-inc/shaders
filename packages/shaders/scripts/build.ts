/**
 * Copy framework builds to dist
 */
async function copyFrameworkBuilds() {
  const frameworks = [
    { name: 'vue', source: 'packages/vue/dist', target: 'vue', hasCodegen: true },
    { name: 'react', source: 'packages/react/dist', target: 'react', hasCodegen: true },
    { name: 'svelte', source: 'packages/svelte/dist', target: 'svelte', hasCodegen: true },
    { name: 'solid', source: 'packages/solid/dist', target: 'solid', hasCodegen: true },
    { name: 'js', source: 'packages/js/dist', target: 'js', hasCodegen: true },
    { name: 'partner', source: 'packages/partner/dist', target: 'partner', hasCodegen: false }
  ]

  for (const framework of frameworks) {
    const sourcePath = path.join(rootDir, framework.source)
    const targetPath = path.join(distDir, framework.target)

    if (!await fs.pathExists(sourcePath)) {
      throw new Error(`${framework.name} dist not found at: ${sourcePath}. Run 'pnpm run build' in ${framework.name} package first.`)
    }

    await fs.copy(sourcePath, targetPath)

    // Create re-export files for codegen (only for framework packages that have it)
    if (framework.hasCodegen) {
      const codegenSource = path.join(targetPath, 'utils/generatePresetCode.js')
      if (await fs.pathExists(codegenSource)) {
        const codegenTarget = path.join(distDir, framework.target, 'codegen.js')
        await fs.writeFile(codegenTarget, `export * from './utils/generatePresetCode.js'`)

        const codegenTypesSource = path.join(targetPath, 'utils/generatePresetCode.d.ts')
        if (await fs.pathExists(codegenTypesSource)) {
          const codegenTypesTarget = path.join(distDir, framework.target, 'codegen.d.ts')
          await fs.writeFile(codegenTypesTarget, `export * from './utils/generatePresetCode'`)
        }
      }
    }
  }
}

/**
 * Generate registry from core package
 */
async function generateRegistry() {
  const coreRegistryPath = path.join(rootDir, 'packages/core/dist/registry.js')

  if (!await fs.pathExists(coreRegistryPath)) {
    throw new Error(`Core registry dist not found at: ${coreRegistryPath}. Run 'pnpm run build' in core package first.`)
  }

  // Import registry module
  const registryModule = await import(`file://${coreRegistryPath}`)

  if (!registryModule.getAllShaders) {
    throw new Error('getAllShaders function not found in registry module')
  }

  const shaders: ShaderMetadata[] = registryModule.getAllShaders().map((shader: any) => ({
    name: shader.name,
    category: shader.category,
    description: shader.definition?.description || shader.description,
    fileName: shader.fileName,
    requiresChild: shader.definition?.requiresChild,
    definition: shader.definition,
    propsMetadata: shader.propsMetadata
  }))

  // Generate registry module content
  const registryContent = `// Auto-generated shader registry
// DO NOT EDIT - This file is generated by the build process

export const shaderRegistry = ${JSON.stringify(shaders, null, 2)}

/**
 * Deprecated (renamed) shader names → canonical name, from each definition's deprecatedNames.
 * The registry lists canonical names only; lookups resolve through this map.
 */
export const deprecatedShaderNames = (() => {
  const map = {}
  for (const shader of shaderRegistry) {
    for (const oldName of shader.definition?.deprecatedNames ?? []) {
      map[oldName] = shader.name
    }
  }
  return map
})()

/**
 * Canonical shader name for \`name\` — resolves deprecated names, passes everything else through.
 */
export function resolveShaderName(name) {
  if (shaderRegistry.some(shader => shader.name === name)) return name
  return deprecatedShaderNames[name] ?? name
}

/**
 * Get all available shaders with their metadata
 * @returns Array of shader metadata objects
 */
export function getAllShaders() {
  return shaderRegistry
}

/**
 * Get a specific shader by name
 * @param name - The shader name (e.g., 'LinearGradient')
 * @returns Shader metadata or undefined if not found
 */
export function getShaderByName(name) {
  const canonical = resolveShaderName(name)
  return shaderRegistry.find(shader => shader.name === canonical)
}

/**
 * Get all shaders in a specific category
 * @param category - The category name (e.g., 'Blurs')
 * @returns Array of shaders in the category
 */
export function getShadersByCategory(category) {
  return shaderRegistry.filter(shader => shader.category === category)
}

/**
 * Get all unique categories
 * @returns Array of category names
 */
export function getCategories() {
  return [...new Set(shaderRegistry.map(shader => shader.category))]
}
`

  // Write registry file
  const registryPath = path.join(distDir, 'registry.js')
  await fs.writeFile(registryPath, registryContent)

  // Generate TypeScript declarations
  const registryTypes = `// Auto-generated shader registry types
// DO NOT EDIT - This file is generated by the build process

export interface ShaderMetadata {
  name: string
  category: string
  description?: string
  fileName: string
  requiresChild?: boolean
  definition?: any
  propsMetadata?: Record<string, any>
}

export declare const shaderRegistry: ShaderMetadata[]
export declare const deprecatedShaderNames: Record<string, string>
export declare function resolveShaderName(name: string): string
export declare function getAllShaders(): ShaderMetadata[]
export declare function getShaderByName(name: string): ShaderMetadata | undefined
export declare function getShadersByCategory(category: string): ShaderMetadata[]
export declare function getCategories(): string[]
`

  const registryTypesPath = path.join(distDir, 'registry.d.ts')
  await fs.writeFile(registryTypesPath, registryTypes)

  return shaders.length
}

/**
 * Recursively find all files matching a pattern
 */
async function findFiles(dir: string, pattern: RegExp): Promise<string[]> {
  const files: string[] = []
  const entries = await fs.readdir(dir, { withFileTypes: true })

  for (const entry of entries) {
    const fullPath = path.join(dir, entry.name)
    if (entry.isDirectory()) {
      files.push(...await findFiles(fullPath, pattern))
    } else if (pattern.test(entry.name)) {
      files.push(fullPath)
    }
  }

  return files
}

